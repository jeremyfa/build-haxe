#!/usr/bin/env bash
# Install the toolchains needed by a list of test targets and write the
# environment file the tests source.
# Usage: scripts/test/setup-tools.sh <target> <test targets, comma separated>
# Output: <test tools dir>/test-env-<profile>.sh (prints its path)
#
# Each scripts/test/tool-<name>.sh installs one toolchain (pinned archive,
# checked sha256) and prints "path:<dir>" and "env:<NAME>=<value>" lines.

source "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/common.sh"
load_profile
source "$ROOT/scripts/test/common-test.sh"

target="${1:?usage: setup-tools.sh <target> <test targets>}"
tests="${2:?usage: setup-tools.sh <target> <test targets>}"

# Toolchains used by each RunCi target (RunCi would install them itself
# otherwise, unpinned and outside the project).
tools_for() {
    case "$1" in
        # a few macro tests run python3, node and javac (Issue11737 on 4.3)
        macro) echo "python node jdk" ;;
        neko) echo "" ;;
        python) echo "python" ;;
        # the server tests use hxjava; deasync (sys tests) is a native addon
        # built with node-gyp, which needs python3
        js) echo "node python jdk deasync" ;;
        php) echo "php" ;;
        hl) echo "hashlink" ;;
        lua) echo "python lua" ;;
        jvm|java) echo "jdk" ;;
        *) echo "" ;;
    esac
}

needed=""
for t in $(echo "$tests" | tr ',' ' '); do
    for tool in $(tools_for "$t"); do
        in_list "$tool" "$needed" || needed="$needed $tool"
    done
done

dir="$(test_tools_dir "$target")"
mkdir -p "$dir"
envfile="$dir/test-env-$HAXE_PROFILE.sh"
paths=""
exports=""
for tool in $needed; do
    log "test toolchain: $tool"
    out="$("$ROOT/scripts/test/tool-$tool.sh" "$target")"
    while IFS= read -r line; do
        case "$line" in
            # also applied here, for the tools that need the previous ones
            path:*) paths="${line#path:}:$paths"; export PATH="${line#path:}:$PATH" ;;
            env:*) exports="$exports
export ${line#env:}"; export "${line#env:}" ;;
        esac
    done <<< "$out"
done

{
    echo "# Generated by scripts/test/setup-tools.sh for: $tests"
    echo "export PATH=\"${paths}\$PATH\""
    echo "$exports"
} > "$envfile"
echo "$envfile"
