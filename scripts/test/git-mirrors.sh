#!/usr/bin/env bash
# Local git mirrors of the pinned test repositories, and the git config that
# sends RunCi's `git clone` and `haxelib git` calls to them.
# Usage: scripts/test/git-mirrors.sh <test home>
# Writes <test home>/.gitconfig (the tests run with HOME=<test home>).
#
# Each mirror is a bare repository holding one commit with the files of the
# pinned commit of TEST_GIT_<N> (from its checked archive), with every branch
# of TEST_GIT_<N>_BRANCHES and HEAD on it. Whatever branch RunCi asks for, it
# gets the pinned files. The commit itself is new (its id differs from the
# original one), which is fine since nothing checks out a commit by id: the
# libraries RunCi would install at a given commit are installed beforehand by
# haxelibs.sh, so RunCi skips them.

source "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/common.sh"
load_profile
source "$ROOT/scripts/test/common-test.sh"

home="${1:?usage: git-mirrors.sh <test home>}"
mkdir -p "$home"
mirrors="$CACHE_DIR/test-tools/git-mirrors"
mkdir -p "$mirrors"

gitconfig="$home/.gitconfig.$$"
{
    echo "# Generated by scripts/test/git-mirrors.sh"
    echo "[user]"
    echo "    name = build-haxe"
    echo "    email = build-haxe@localhost"
    echo "[advice]"
    echo "    detachedHead = false"
    echo "[init]"
    echo "    defaultBranch = master"
    echo "[safe]"
    echo "    directory = *"
} > "$gitconfig"

for n in $TEST_GIT_DEPS; do
    v="TEST_GIT_${n}_REPO"; repo="${!v}"
    v="TEST_GIT_${n}_COMMIT"; commit="${!v}"
    v="TEST_GIT_${n}_BRANCHES"; branches="${!v:-master main}"
    lower="$(git_dep_name "$n")"
    mirror="$mirrors/$lower-${commit:0:12}.git"
    if [ ! -f "$mirror/.done" ]; then
        src="$(git_dep_src "$n")"
        [ ! -e "$mirror" ] || mv "$mirror" "$mirror.old.$(date +%Y%m%d%H%M%S)"
        work="$mirrors/work-$lower-${commit:0:12}"
        mkdir -p "$work"
        cp -R "$src/." "$work/"
        (
            cd "$work"
            export GIT_AUTHOR_NAME=build-haxe GIT_AUTHOR_EMAIL=build-haxe@localhost
            export GIT_COMMITTER_NAME=build-haxe GIT_COMMITTER_EMAIL=build-haxe@localhost
            export GIT_AUTHOR_DATE="2000-01-01T00:00:00Z" GIT_COMMITTER_DATE="2000-01-01T00:00:00Z"
            git init -q
            git add -A
            git -c commit.gpgsign=false commit -q -m "$repo at $commit"
        )
        git init -q --bare "$mirror.tmp.$$"
        for b in $branches; do
            git -C "$work" push -q "$mirror.tmp.$$" "HEAD:refs/heads/$b"
        done
        git -C "$mirror.tmp.$$" symbolic-ref HEAD "refs/heads/$(echo "$branches" | awk '{print $1}')"
        mv "$mirror.tmp.$$" "$mirror"
        touch "$mirror/.done"
        log "git mirror: $repo at ${commit:0:12}"
    fi
    url="$(file_url "$mirror")"
    # git uses the longest matching prefix, so the ".git" and "/" forms win
    # over the plain one.
    {
        echo "[url \"$url\"]"
        echo "    insteadOf = $repo"
        echo "    insteadOf = $repo.git"
        echo "    insteadOf = $repo/"
    } >> "$gitconfig"
done

mv -f "$gitconfig" "$home/.gitconfig"
